		THE MORALITY OF LABOR STRIKES

		Strike Action - a collective action undertaken by group of workers in the form of a refusal to perform a work.

		Types of Strikes:
		1. Sit-Down Strike(Sit-in) - workers show up to work but refuse to work
		2. General Strike - strike affecting all areas of a labor force across many industries
		3. Sympathy Strike - strike  initiated by workers in one industry and supported by workers in a separate but related industry
		4. Unfair Labor Practice Strike - action taken by an employer that is believed to be inimical to the interest of an employee organization
		5. Jurisdictional Strike - refusal to work undertaken by a union to assert it's members right
		6. Economic Strike - based on demand for better wages
		7. Wildcat Strike - against the will of the leadership of the union
		8. Slow-Down - form of stoppage in which employees reduce their individual production
		9. Recognition Strike - forcing employers to recognize them

		Whistleblowing - disclosure by an employee of confidential information which relates to some danger
		Whistleblower - someone who witnesses behavior by members that is either contrary to the mission of the organization

		Types of Whistleblowing
		1. Internal - occurs within the organization
		2. External - occurs outside the organization
		3. Current - those who blow the whistle on present employers
		4. Alumni - those who blow the whistle on former employers
		5. Open - whistleblower discloses his identity
		6. Anonymous - whistleblower does not disclose his identity

